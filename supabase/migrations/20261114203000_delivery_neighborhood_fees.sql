create table if not exists public.delivery_neighborhood_fees (
  id bigint generated by default as identity primary key,
  neighborhood text not null,
  normalized_name text not null unique check (normalized_name ~ '^[a-z0-9]+$'),
  zone_number smallint not null check (zone_number between 1 and 4),
  delivery_fee numeric(8,2) not null check (delivery_fee > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists delivery_neighborhood_fees_active_zone_idx
  on public.delivery_neighborhood_fees (active, zone_number);

alter table public.delivery_neighborhood_fees enable row level security;
grant select on public.delivery_neighborhood_fees to anon, authenticated;
grant all on public.delivery_neighborhood_fees to service_role;
revoke insert, update, delete on public.delivery_neighborhood_fees from anon, authenticated;

create policy "Public can read active delivery neighborhoods"
  on public.delivery_neighborhood_fees
  for select to anon, authenticated
  using (active = true);

comment on table public.delivery_neighborhood_fees is
  'Tabela única de bairros atendidos e taxas de entrega da Nutrifit. Atualização somente por equipe autorizada.';


-- Centraliza as taxas e a cobertura de entrega em uma única fonte de verdade.
create table public.delivery_zone_neighborhoods (
  normalized_name text primary key,
  neighborhood text not null check (char_length(trim(neighborhood)) between 1 and 120),
  zone text not null check (zone in ('Zona 1', 'Zona 2', 'Zona 3', 'Zona 4')),
  fee numeric(10,2) not null check (fee >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint delivery_zone_neighborhoods_normalized_name_check
    check (char_length(trim(normalized_name)) between 1 and 120)
);

comment on table public.delivery_zone_neighborhoods is
  'Fonte única das taxas de entrega da Nutrifit por bairro. Leitura pública apenas para registros ativos; gravação somente por migração/administrador.';
comment on column public.delivery_zone_neighborhoods.normalized_name is
  'Nome normalizado sem acentos e em minúsculas, usado para busca exata por bairro.';

create index delivery_zone_neighborhoods_active_zone_idx
  on public.delivery_zone_neighborhoods (active, zone);

alter table public.delivery_zone_neighborhoods enable row level security;
revoke all on table public.delivery_zone_neighborhoods from public, anon, authenticated, service_role;
grant select on table public.delivery_zone_neighborhoods to anon, authenticated, service_role;
create policy delivery_zone_neighborhoods_public_read_active
  on public.delivery_zone_neighborhoods
  for select
  to anon, authenticated
  using (active = true);


create table if not exists public.public_order_rate_limits (
  id bigint generated by default as identity primary key,
  identifier_hash text not null,
  scope text not null,
  created_at timestamptz not null default now()
);

create index if not exists public_order_rate_limits_lookup_idx
  on public.public_order_rate_limits (identifier_hash, scope, created_at desc);

alter table public.public_order_rate_limits enable row level security;

revoke all on table public.public_order_rate_limits from public, anon, authenticated;
grant all on table public.public_order_rate_limits to service_role;

create or replace function public.consume_public_order_rate_limit(
  p_identifier_hash text,
  p_scope text,
  p_window_seconds integer,
  p_max_requests integer
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  recent_count integer;
begin
  if p_identifier_hash is null or p_identifier_hash !~ '^[a-f0-9]{64}$' then
    return false;
  end if;
  if p_scope not in (
    'customer-order:ip', 'customer-order:phone',
    'combo-order:ip', 'combo-order:phone'
  ) then
    return false;
  end if;
  if p_window_seconds not in (600, 86400) or p_max_requests < 1 or p_max_requests > 1000 then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtext(p_identifier_hash || ':' || p_scope || ':' || p_window_seconds::text));

  delete from public.public_order_rate_limits
    where created_at < now() - interval '24 hours';

  select count(*) into recent_count
    from public.public_order_rate_limits
    where identifier_hash = p_identifier_hash
      and scope = p_scope
      and created_at > now() - make_interval(secs => p_window_seconds);

  if recent_count >= p_max_requests then
    return false;
  end if;

  insert into public.public_order_rate_limits (identifier_hash, scope)
    values (p_identifier_hash, p_scope);

  return true;
end;
$function$;

revoke all on function public.consume_public_order_rate_limit(text, text, integer, integer)
  from public, anon, authenticated;
grant execute on function public.consume_public_order_rate_limit(text, text, integer, integer)
  to service_role;
